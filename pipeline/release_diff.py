#!/usr/bin/env python3
"""What changed between two releases' knowledge DBs -- a generated report, not a
storage format (each release DB stays complete; plan Decision 8).

Per app present in both: fields added / removed, fields moved (same EQU name,
new position) and jBC names renamed (same EQU field and component, different
componentised name). Plus apps added / removed.

  python pipeline/release_diff.py --old R23 --new R25 --out build/releases/R23-to-R25
  (writes <out>.md and <out>.json)
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

from releases import open_release_db


def _fields(conn):
    by_app = defaultdict(dict)
    for app, name, pos in conn.execute("SELECT app, field_name, position FROM fields"):
        by_app[app][name] = pos
    return by_app


def _jbc(conn):
    """{(app, field_name, component): 'Comp.Record.Field'}; empty if the table is missing."""
    try:
        rows = conn.execute("SELECT app, field_name, component, record, comp_field FROM component_fields").fetchall()
    except Exception:
        return {}
    return {(a, f, c): f"{c}.{r}.{cf}" for a, f, c, r, cf in rows}


def diff_releases(old, new):
    of, nf = _fields(old), _fields(new)
    oj, nj = _jbc(old), _jbc(new)
    renamed = defaultdict(list)  # one pass over the shared keys, not one per app
    for key in sorted(set(oj) & set(nj)):
        if oj[key] != nj[key]:
            renamed[key[0]].append([key[1], oj[key], nj[key]])
    apps = {}
    for app in sorted(set(of) & set(nf)):
        o, n = of[app], nf[app]
        entry = {
            "fields_added": sorted(set(n) - set(o)),
            "fields_removed": sorted(set(o) - set(n)),
            "fields_moved": [[f, o[f], n[f]] for f in sorted(set(o) & set(n)) if o[f] != n[f]],
            "jbc_renamed": renamed.get(app, []),
        }
        if any(entry.values()):
            apps[app] = entry
    summary = {
        "apps_added": len(set(nf) - set(of)),
        "apps_removed": len(set(of) - set(nf)),
        "apps_changed": len(apps),
    }
    for key in ("fields_added", "fields_removed", "fields_moved", "jbc_renamed"):
        summary[key] = sum(len(a[key]) for a in apps.values())
    return {
        "summary": summary,
        "apps_added": sorted(set(nf) - set(of)),
        "apps_removed": sorted(set(of) - set(nf)),
        "apps": apps,
    }


def render_markdown(diff, old_name, new_name):
    s = diff["summary"]
    lines = [f"# {old_name} → {new_name}: knowledge changes", "",
             "Generated by `pipeline/release_diff.py` from the two complete release DBs.", "",
             "## Summary", "", "| Change | Count |", "|---|---|"]
    lines += [f"| {k.replace('_', ' ')} | {v:,} |" for k, v in s.items()]
    for title, key in (("Applications added", "apps_added"), ("Applications removed", "apps_removed")):
        lines += ["", f"## {title} ({len(diff[key])})", ""]
        lines += [", ".join(f"`{a}`" for a in diff[key])] if diff[key] else ["None."]
    lines += ["", f"## Changed applications ({len(diff['apps'])})"]
    for app, e in diff["apps"].items():
        lines += ["", f"### {app}", ""]
        if e["fields_added"]:
            lines.append("- Added: " + ", ".join(f"`{f}`" for f in e["fields_added"]))
        if e["fields_removed"]:
            lines.append("- Removed: " + ", ".join(f"`{f}`" for f in e["fields_removed"]))
        if e["fields_moved"]:
            lines.append("- Moved: " + ", ".join(f"`{f}` {a} → {b}" for f, a, b in e["fields_moved"]))
        if e["jbc_renamed"]:
            lines.append("- jBC renamed: " + ", ".join(f"`{f}` `{a}` → `{b}`" for f, a, b in e["jbc_renamed"]))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", required=True)
    ap.add_argument("--new", required=True)
    ap.add_argument("--out", help="output path without extension (default build/releases/<old>-to-<new>)")
    args = ap.parse_args()
    old, new = open_release_db(args.old), open_release_db(args.new)
    diff = diff_releases(old, new)
    out = Path(args.out or f"build/releases/{args.old}-to-{args.new}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(diff, indent=1), encoding="utf-8")
    out.with_suffix(".md").write_text(render_markdown(diff, args.old, args.new), encoding="utf-8")
    print(json.dumps(diff["summary"]))
    print(f"Wrote {out}.md and {out}.json")


if __name__ == "__main__":
    main()
