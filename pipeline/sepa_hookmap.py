#!/usr/bin/env python3
"""Recover the configuration-field → Java-hook-method wiring for the payment domain.

TPH names its extension points inside the *field descriptions* of its
configuration applications: a field like ``PP.CG.BulkingCriteriaAPI`` says which
``EB.API`` HOOK record implements it and which hook method it dispatches to.

This scans the payment-domain ``table-schema/*.md`` files for those statements and
renders them as ``knowledge/sepa/config-hook-map.md``, so no interface has to be
guessed.

Usage:
    python pipeline/sepa_hookmap.py \
        --schema skills/temenos-dev/references/table-schema \
        --out knowledge/sepa
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

# Applications whose field descriptions are worth scanning.
APP_PREFIXES = ("PP.", "PPT.", "PI.", "PAYMENT.", "POR.", "PW.")

ROW = re.compile(r"^\|\s*(\d+)\s*\|\s*`([^`]+)`\s*\|")
# "...defined in the EB.API record PP.CLEARING.BulkingCriteriaAPI.HOOK."
HOOK_RECORD = re.compile(r"EB\.API record\s+([A-Za-z0-9_.]+\.HOOK)")
# "...supports the PaymentLifecycle.getGroupingCriteria() method."
HOOK_METHOD = re.compile(r"supports the\s+([A-Za-z0-9_]+\.[A-Za-z0-9_]+)\(\)")
# "...which is in PP_PaymentLifecycleHook.jar shipped with T24."
HOOK_JAR = re.compile(r"([A-Za-z0-9_]+\.jar)")
HOOK_PKG = re.compile(r"(com\.temenos\.t24\.api\.hook[A-Za-z0-9_.]*)")


def scan(schema_dir: Path) -> list[dict]:
    found: list[dict] = []
    for path in sorted(schema_dir.glob("*.md")):
        app = path.stem
        if not app.startswith(APP_PREFIXES):
            continue
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            m = ROW.match(line)
            if not m:
                continue
            if ".HOOK" not in line and "supports the" not in line:
                continue
            rec = HOOK_RECORD.search(line)
            meth = HOOK_METHOD.search(line)
            if not rec and not meth:
                continue
            pkg = HOOK_PKG.search(line)
            jar = HOOK_JAR.search(line)
            found.append({
                "app": app,
                "position": m.group(1),
                "field": m.group(2),
                "hook_record": rec.group(1) if rec else "",
                "hook_method": meth.group(1) if meth else "",
                "package": pkg.group(1) if pkg else "",
                "jar": jar.group(1) if jar else "",
            })
    return found


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--schema", type=Path,
                    default=Path("skills/temenos-dev/references/table-schema"))
    ap.add_argument("--out", type=Path, default=Path("knowledge/sepa"))
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    rows = scan(args.schema)

    lines = [
        "# SEPA / TPH — Configuration Field → Hook Method Map",
        "",
        "> Generated by `pipeline/sepa_hookmap.py` by scanning the field descriptions in",
        "> `skills/temenos-dev/references/table-schema/*.md` (which come from JavaDoc HTML",
        "> attached to the `INSERTS/I_F.<APP>` field definitions). Every row is quoted",
        "> product documentation, not inference.",
        "",
        "> **This is the answer to \"what interface does my custom API have to implement?\"**",
        "> Set the configuration field to an `EB.API` record of type `METHOD`; that record",
        "> implements the interface defined in the named `.HOOK` `EB.API` record; your class",
        "> subclasses the hook class and overrides the named method. Exact signatures are in",
        "> [`java-api.md`](java-api.md).",
        "",
        f"{len(rows)} wired configuration fields found.",
        "",
        "| Application | Pos | Configuration field | `EB.API` HOOK record | Hook method | JAR |",
        "|-------------|-----|---------------------|----------------------|-------------|-----|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['app']}` | {r['position']} | `{r['field']}` | "
            f"{'`' + r['hook_record'] + '`' if r['hook_record'] else '—'} | "
            f"{'`' + r['hook_method'] + '()`' if r['hook_method'] else '—'} | "
            f"{'`' + r['jar'] + '`' if r['jar'] else '—'} |"
        )
    lines.append("")

    (args.out / "config-hook-map.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out / 'config-hook-map.md'} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
