#!/usr/bin/env python3
"""Dump exact method signatures for the payment-domain hook APIs.

Runs ``javap`` against each hook class in its own JAR (never the whole JAR set —
a 2,000-entry classpath makes javap unusably slow) and renders the result as
``knowledge/sepa/java-api.md``.

Signatures here are read from bytecode, so they are exact: parameter order,
generic types and return types can be relied on when writing an L3 override.

Usage:
    python pipeline/sepa_javap.py --jars jar --out knowledge/sepa \
        --raw work/javap
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

# (jar stem, fully-qualified class) — the customisation surface of the payment
# domain, as found by pipeline/sepa_extract.py.
HOOKS = [
    ("PP_PaymentLifecycleHook", "com.temenos.t24.api.hook.payments.PaymentLifecycle"),
    ("PI_PaymentOrderLifecycleHook", "com.temenos.t24.api.hook.payments.PaymentOrderLifecycle"),
    ("PI_PaymentOrderHook", "com.temenos.t24.api.hook.PaymentOrderHook"),
    ("PP_MessageHook", "com.temenos.t24.api.hook.payments.Message"),
    ("PP_ComponentApiHook", "com.temenos.t24.api.hook.ComponentApiHook"),
    ("PP_MessageAcceptanceParamHook", "com.temenos.t24.api.hook.MessageAcceptanceParamHook"),
    ("PP_FeeDeterminationHook", "com.temenos.t24.api.hook.FeeDeterminationHook"),
    ("PP_BalanceCheckApiHook", "com.temenos.t24.api.hook.BalanceCheckApiHook"),
    ("PP_PostingSchemeAPIHook", "com.temenos.t24.api.hook.PostingSchemeAPIHook"),
    ("PP_DataAccessApi", "com.temenos.t24.api.payments.DataAccess"),
    ("PW_ProcessHook", "com.temenos.t24.api.hook.foundation.Process"),
    ("DD_ContractHook", "com.temenos.t24.api.hook.contract.DirectDebit"),
    ("DB_DebitCollectionOrderHook", "com.temenos.t24.api.hook.DebitCollectionOrderHook"),
    ("FT_ClearingHook", "com.temenos.t24.api.hook.clearing.InwardEntry"),
    ("AC_ClearingServiceHook", "com.temenos.t24.api.hook.accounting.ClearingService"),
    ("ACHFRM_ClearingHouseHook", "com.temenos.t24.api.hook.countrymodelbank.usa.Clearing"),
]

# Boilerplate every TAFJ-generated class carries; noise in an API reference.
BOILERPLATE = re.compile(
    r"^\s*(protected static final com\.temenos\.logging|"
    r"private final com\.temenos\.tafj|"
    r"public static java\.lang\.String get(Version|BuildDate|ComponentVersion)\(\)|"
    r"static \{\};)"
)


def javap(jar: Path, cls: str) -> str:
    result = subprocess.run(
        ["javap", "-classpath", str(jar), "-p", cls],
        capture_output=True, text=True, timeout=120,
    )
    if result.returncode != 0:
        return f"!! javap failed: {result.stderr.strip()}"
    return result.stdout


def shorten(sig: str) -> str:
    """Drop the shared package prefixes so signatures fit on a page."""
    sig = sig.replace("com.temenos.t24.api.complex.", "~complex.")
    sig = sig.replace("com.temenos.t24.api.records.", "~records.")
    sig = sig.replace("com.temenos.t24.api.hook.", "~hook.")
    sig = sig.replace("java.lang.String", "String")
    sig = sig.replace("java.util.List", "List")
    sig = sig.replace("com.temenos.api.", "")
    return sig.strip().rstrip(";")


def dto_getters(cache_dir: Path, jar_stem: str, package: str) -> list[tuple[str, list[str]]]:
    """Return [(dto_simple_name, [getter/setter names])] for one complex package."""
    path = cache_dir / f"{jar_stem}.json"
    if not path.exists():
        return []
    entry = json.loads(path.read_text(encoding="utf-8"))
    out = []
    for cls in entry.get("classes", []):
        if cls.get("package") != package:
            continue
        accessors = sorted(
            m["name"] for m in cls.get("methods", [])
            if m["name"].startswith(("get", "set", "is")) and m.get("is_public")
        )
        if accessors:
            out.append((cls["name"], accessors))
    return sorted(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--jars", type=Path, default=Path("jar"))
    ap.add_argument("--cache", type=Path, default=Path("cache"))
    ap.add_argument("--out", type=Path, default=Path("knowledge/sepa"))
    ap.add_argument("--raw", type=Path, default=Path("work/javap"))
    args = ap.parse_args()

    if not shutil.which("javap"):
        raise SystemExit("javap not found on PATH — install a JDK or add it to PATH")

    args.out.mkdir(parents=True, exist_ok=True)
    args.raw.mkdir(parents=True, exist_ok=True)

    lines = [
        "# SEPA / TPH — Java Hook API Reference",
        "",
        "> Generated by `pipeline/sepa_javap.py`. Every signature below is read from",
        "> compiled bytecode with `javap -p`, so parameter order, generic types and",
        "> return types are exact. Raw `javap` output is kept under `work/javap/`.",
        "",
        "> Package prefixes are abbreviated for width:",
        "> `~complex.` = `com.temenos.t24.api.complex.`,",
        "> `~records.` = `com.temenos.t24.api.records.`,",
        "> `~hook.` = `com.temenos.t24.api.hook.`.",
        "",
        "> **These classes are extended, not called.** An L3 customisation subclasses",
        "> the hook and overrides the method it needs; T24 invokes the override through",
        "> an `EB.API` record of type `METHOD` referenced from the relevant configuration",
        "> field (for example `PP.CLEARING` `PP.CG.BulkingCriteriaAPI` →",
        "> `PaymentLifecycle.getGroupingCriteria`).",
        "",
    ]

    missing = []
    for jar_stem, cls in HOOKS:
        jar = args.jars / f"{jar_stem}.jar"
        simple = cls.rsplit(".", 1)[-1]
        if not jar.exists():
            missing.append((jar_stem, cls))
            continue

        raw = javap(jar, cls)
        (args.raw / f"{simple}.javap").write_text(raw, encoding="utf-8")

        sigs = []
        for ln in raw.splitlines():
            if not ln.startswith("  ") or BOILERPLATE.match(ln):
                continue
            body = ln.strip()
            # Constructors carry no override value — the name before "(" ends
            # with the class's own simple name and there is no return type.
            head = body.split("(")[0]
            if head.split()[-1].endswith("." + simple) and len(head.split()) == 2:
                continue
            sigs.append(shorten(ln))

        lines += [
            f"## `{cls}`",
            "",
            f"JAR: `{jar.name}`",
            "",
        ]
        if sigs:
            lines.append("```java")
            lines += sigs
            lines.append("```")
        else:
            lines.append("_No overridable methods found in this class._")
        lines.append("")

        # Complex DTOs used by this hook.
        pkg_guess = "com.temenos.t24.api.complex." + jar_stem.lower().replace("_", ".", 1)
        dtos = dto_getters(args.cache, jar_stem, pkg_guess)
        if dtos:
            lines += [
                f"### Complex types — `{pkg_guess}`",
                "",
                "| Type | Accessors |",
                "|------|-----------|",
            ]
            for name, accessors in dtos:
                lines.append(f"| `{name}` | {', '.join(f'`{a}`' for a in accessors)} |")
            lines.append("")

    if missing:
        lines += ["## Not found in this JAR set", ""]
        for jar_stem, cls in missing:
            lines.append(f"- `{cls}` — expected in `{jar_stem}.jar`, JAR absent")
        lines.append("")

    (args.out / "java-api.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out / 'java-api.md'} "
          f"({len(HOOKS) - len(missing)} hooks, {len(missing)} missing)")


if __name__ == "__main__":
    main()
